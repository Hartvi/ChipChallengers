"""Place a Lua race and render its gate preview from the generated circuit mesh."""
import bpy
import math
import json
import uuid
from pathlib import Path
from mathutils import Vector

ROOT = Path(__file__).resolve().parents[2]
OUT = Path('C:/Users/Acer/BlenderTests/industrial-test-track')
SCENARIO = ROOT / 'Assets/StreamingAssets/Scenarios/industrial_test_track_race.lua'
bpy.ops.wm.open_mainfile(filepath=str(OUT/'industrial_test_track.blend'))
road = bpy.data.objects['Circuit and graded runoff']
# Each row has twelve lateral samples; indices five and six bracket the road centre.
points = [(road.data.vertices[i+5].co + road.data.vertices[i+6].co)*0.5 for i in range(0,len(road.data.vertices),12)]
lengths = [0.0]
for i in range(len(points)):
    lengths.append(lengths[-1]+(points[(i+1)%len(points)]-points[i]).length)
lap = lengths[-1]

# point_at interpolates a centreline position by distance along the lap.
def point_at(distance):
    distance %= lap
    for i in range(len(points)):
        if lengths[i+1] >= distance:
            blend = (distance-lengths[i])/(lengths[i+1]-lengths[i])
            return points[i].lerp(points[(i+1)%len(points)],blend)
    return points[0].copy()

# game_point matches OBJ Y-up export followed by the current importer's X reflection.
def game_point(point, height):
    return [-point.x, point.z+height, -point.y]

# lua_vector serializes a game position without locale-dependent decimal formatting.
def lua_vector(point):
    return '{' + ', '.join(f'{value:.3f}' for value in point) + '}'

radius = 8.0
start_distance = 0.0
checkpoint_distances = list(range(80, int(lap-25), 65))
gates = [point_at(start_distance)] + [point_at(distance) for distance in checkpoint_distances]
spawn = point_at(-20)
tangent = point_at(-19)-spawn
yaw = math.degrees(math.atan2(-tangent.x,-tangent.y))
assert (gates[0]-spawn).length > radius+2, 'Spawn intersects the countdown trigger'
assert min((gates[i]-gates[i+1]).length for i in range(len(gates)-1)) > radius*2, 'Consecutive gates overlap'
checkpoints = '\n'.join('        '+lua_vector(game_point(p,1.0))+',' for p in gates[1:])
SCENARIO.write_text('''-- Generated by Tools/MapAuthoring/build_industrial_race.py; positions match the exported map.
Scenario({
    id = "%s",
    title = "Industrial Test Track",
    recordVersion = 1,
    scenarioLogicVersion = 1,
    completionType = "timeTrial",
    rules = {
        forbiddenChipTypes = {},
        maxChips = -1,
        physics = { fixedDeltaTime = 0.001, solverIterations = 1, solverVelocityIterations = 3 }
    }
})

LoadMap("industrial_test_track")
SetPosition("player1", %s)
SetRotation("player1", {0, %.3f, 0})

Race({
    radius = 8,
    start = %s,
    checkpoints = {
%s
    },
    finish = %s
})
''' % (uuid.uuid5(uuid.NAMESPACE_URL,'ChipChallengers/industrial_test_track/time_trial/v1'),
       lua_vector(game_point(spawn,2.0)),yaw,lua_vector(game_point(gates[0],1.0)),checkpoints,
       lua_vector(game_point(gates[0],1.0))),encoding='utf-8')

# Preview-only objects are saved separately and never exported into the map mesh.
def gate_material(name, color):
    material = bpy.data.materials.new(name)
    material.diffuse_color = (*color,0.22)
    material.use_nodes = True
    nodes = material.node_tree.nodes
    nodes.clear()
    output = nodes.new('ShaderNodeOutputMaterial')
    mix = nodes.new('ShaderNodeMixShader')
    mix.inputs[0].default_value = 0.22
    transparent = nodes.new('ShaderNodeBsdfTransparent')
    emission = nodes.new('ShaderNodeEmission')
    emission.inputs['Color'].default_value = (*color,1)
    emission.inputs['Strength'].default_value = 0.8
    links = material.node_tree.links
    links.new(transparent.outputs[0],mix.inputs[1])
    links.new(emission.outputs[0],mix.inputs[2])
    links.new(mix.outputs[0],output.inputs[0])
    return material

start_mat = gate_material('Preview start finish',(0.15,0.9,0.2))
checkpoint_mat = gate_material('Preview checkpoints',(1.0,0.5,0.04))
label_mat = bpy.data.materials.new('Preview labels')
label_mat.diffuse_color = (0.015,0.02,0.025,1)
labels = []
for index,p in enumerate(gates):
    center = p + Vector((0,0,1))
    bpy.ops.mesh.primitive_uv_sphere_add(segments=24,ring_count=12,radius=radius,location=center)
    obj=bpy.context.object
    obj.name='PREVIEW_Start_Finish' if index==0 else f'PREVIEW_Checkpoint_{index:02d}'
    obj.data.materials.append(start_mat if index==0 else checkpoint_mat)
    bpy.ops.object.text_add(location=center+Vector((0,0,10)))
    text=bpy.context.object
    text.name=f'PREVIEW_Label_{index:02d}'
    text.data.body='START / FINISH' if index==0 else str(index)
    text.data.align_x='CENTER'
    text.data.align_y='CENTER'
    text.data.size=4 if index==0 else 6
    text.data.materials.append(label_mat)
    labels.append(text)
scene=bpy.context.scene
scene.cycles.samples=24
for name in ['overview','layout','start_straight']:
    camera=bpy.data.objects[name]
    scene.camera=camera
    for label in labels: label.rotation_euler=camera.rotation_euler
    scene.render.filepath=str(OUT/f'race_{name}.png')
    bpy.ops.render.render(write_still=True)
scene.camera=bpy.data.objects['overview']
for label in labels: label.rotation_euler=scene.camera.rotation_euler
bpy.ops.wm.save_as_mainfile(filepath=str(OUT/'industrial_race_preview.blend'))
(OUT/'race_waypoints.json').write_text(json.dumps({'map':'industrial_test_track','spawn':game_point(spawn,2),
    'yaw_degrees':yaw,'gate_radius':radius,'start_finish':game_point(gates[0],1),
    'checkpoints':[game_point(p,1) for p in gates[1:]],'checkpoint_distances':checkpoint_distances},indent=2))
print('SCENARIO_OUTPUT:',SCENARIO)
print('CHECKPOINTS:',len(gates)-1)
